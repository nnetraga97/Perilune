#!/usr/bin/env python3
"""Compile a checked, runtime-only NRHO reference revolution from locked SPICE kernels.

This authoring script performs no network access. Use
scripts/fetch-artemis-reference-kernels.mjs explicitly before running it.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import struct
import sys
from typing import Any

EXPECTED_SPICEYPY_VERSION = "8.1.2"
EXPECTED_NUMPY_VERSION = "2.5.1"
SECONDS_PER_DAY = 86_400.0
KILOMETERS_TO_METERS = 1_000.0


def repository_root() -> Path:
    return Path(__file__).resolve().parent.parent


def parse_args() -> argparse.Namespace:
    root = repository_root()
    parser = argparse.ArgumentParser(
        description="Compile the Artemis IV generic Gateway NRHO reference artifact"
    )
    parser.add_argument(
        "--source-lock",
        type=Path,
        default=root / "assets/missions/artemis-iv/sources/source.lock.json",
    )
    parser.add_argument(
        "--kernel-dir",
        type=Path,
        default=root / "assets/missions/artemis-iv/sources/kernels",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=root / "src/generated/artemis-iv-reference-track.json",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Compare generated bytes with the checked artifact instead of writing it",
    )
    return parser.parse_args()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def verify_kernel(path: Path, source: dict[str, Any]) -> None:
    artifact = source.get("artifact")
    if not isinstance(artifact, dict):
        raise ValueError(f"{source.get('id', 'kernel')} has no locked artifact")
    if not path.is_file():
        raise FileNotFoundError(
            f"Missing locked kernel {path}. Run scripts/fetch-artemis-reference-kernels.mjs first."
        )
    actual_size = path.stat().st_size
    if actual_size != artifact.get("byteLength"):
        raise ValueError(
            f"{path.name} byte length changed: expected {artifact.get('byteLength')}, got {actual_size}"
        )
    actual_digest = sha256_file(path)
    if actual_digest != artifact.get("sha256"):
        raise ValueError(
            f"{path.name} SHA-256 changed: expected {artifact.get('sha256')}, got {actual_digest}"
        )


def sample_digest(samples: list[dict[str, Any]]) -> str:
    digest = hashlib.sha256()
    for sample in samples:
        values = (
            sample["tSeconds"],
            *sample["positionM"],
            *sample["velocityMps"],
        )
        digest.update(struct.pack(">7d", *values))
    return digest.hexdigest()


def vector_norm(vector: list[float]) -> float:
    return math.sqrt(sum(value * value for value in vector))


def subtract(left: list[float], right: list[float]) -> list[float]:
    return [left[index] - right[index] for index in range(3)]


def compile_artifact(lock: dict[str, Any], kernel_dir: Path) -> dict[str, Any]:
    try:
        import numpy
        import spiceypy as spice
    except ImportError as error:
        raise RuntimeError(
            "Install the pinned authoring environment from scripts/requirements-artemis-reference.txt"
        ) from error

    if spice.__version__ != EXPECTED_SPICEYPY_VERSION:
        raise RuntimeError(
            f"SpiceyPy must be {EXPECTED_SPICEYPY_VERSION}, got {spice.__version__}"
        )
    if numpy.__version__ != EXPECTED_NUMPY_VERSION:
        raise RuntimeError(f"NumPy must be {EXPECTED_NUMPY_VERSION}, got {numpy.__version__}")

    sources = {source["id"]: source for source in lock.get("sources", [])}
    trajectory = lock.get("referenceTrajectory")
    if not isinstance(trajectory, dict):
        raise ValueError("source lock has no referenceTrajectory")
    kernel_source_ids = trajectory.get("kernelSourceIds")
    if not isinstance(kernel_source_ids, list) or not kernel_source_ids:
        raise ValueError("referenceTrajectory.kernelSourceIds is empty")

    kernel_paths: dict[str, Path] = {}
    for source_id in kernel_source_ids:
        source = sources.get(source_id)
        if not isinstance(source, dict) or source.get("kind") != "kernel":
            raise ValueError(f"Unknown locked kernel source {source_id}")
        filename = source.get("artifact", {}).get("filename")
        if not isinstance(filename, str) or Path(filename).name != filename:
            raise ValueError(f"Unsafe kernel filename for {source_id}")
        path = kernel_dir.resolve() / filename
        verify_kernel(path, source)
        kernel_paths[source_id] = path
    locked_kernel_artifacts = [
        {
            "sourceId": source_id,
            "filename": sources[source_id]["artifact"]["filename"],
            "byteLength": sources[source_id]["artifact"]["byteLength"],
            "sha256": sources[source_id]["artifact"]["sha256"],
        }
        for source_id in kernel_source_ids
    ]

    selection = trajectory.get("selection")
    if not isinstance(selection, dict):
        raise ValueError("referenceTrajectory.selection is missing")
    start_et = float(selection["startEtSeconds"])
    stop_et = float(selection["stopEtSeconds"])
    step = float(selection["sampleStepSeconds"])
    duration = stop_et - start_et
    if not math.isfinite(duration) or duration <= 0 or not math.isfinite(step) or step <= 0:
        raise ValueError("locked sample interval is invalid")

    # Load the time kernel first, then the planetary ephemeris and DSG SPK.
    load_order = [
        "naif-leapseconds-0012",
        "jpl-de440s-spk-2020",
        "naif-dsg-nrho-spk-2018",
    ]
    if set(load_order) != set(kernel_source_ids):
        raise ValueError("kernel set does not match the compiler's reviewed transform")
    for source_id in load_order:
        spice.furnsh(str(kernel_paths[source_id]))

    try:
        relative_times: list[float] = []
        elapsed = 0.0
        while elapsed < duration:
            relative_times.append(elapsed)
            elapsed += step
        if not relative_times or not math.isclose(relative_times[-1], duration, abs_tol=1e-9):
            relative_times.append(duration)

        samples: list[dict[str, Any]] = []
        for t_seconds in relative_times:
            state_km, _ = spice.spkezr("-60000", start_et + t_seconds, "J2000", "NONE", "301")
            position_m = [float(value) * KILOMETERS_TO_METERS for value in state_km[:3]]
            velocity_mps = [float(value) * KILOMETERS_TO_METERS for value in state_km[3:]]
            if not all(math.isfinite(value) for value in (*position_m, *velocity_mps)):
                raise ValueError(f"SPICE returned a non-finite state at t={t_seconds}")
            samples.append(
                {
                    "tSeconds": float(t_seconds),
                    "positionM": position_m,
                    "velocityMps": velocity_mps,
                }
            )

        radii = [vector_norm(sample["positionM"]) for sample in samples]
        endpoint_separation = vector_norm(
            subtract(samples[0]["positionM"], samples[-1]["positionM"])
        )
        endpoint_velocity_delta = vector_norm(
            subtract(samples[0]["velocityMps"], samples[-1]["velocityMps"])
        )
        minimum_radius = min(radii)
        maximum_radius = max(radii)
        period_days = duration / SECONDS_PER_DAY
        if not 3_150_000 <= minimum_radius <= 3_600_000:
            raise ValueError(f"sampled perilune radius is outside the reviewed envelope: {minimum_radius}")
        if not 65_000_000 <= maximum_radius <= 75_000_000:
            raise ValueError(f"sampled apolune radius is outside the reviewed envelope: {maximum_radius}")
        if abs(period_days - 6.562) > 0.35:
            raise ValueError(f"sampled revolution period is outside the reviewed envelope: {period_days}")

        return {
            "schemaVersion": 1,
            "id": trajectory["id"],
            "missionId": "artemis-iv",
            "fidelity": "reference-trajectory",
            "description": (
                "One fixed revolution sampled from NASA/JPL's generic 15-year Gateway NRHO "
                "reference SPK and transformed to a Moon-centered J2000 state."
            ),
            "disclaimer": trajectory["disclaimer"],
            "coordinateFrame": {
                "id": "MOON_J2000",
                "origin": "Moon",
                "originNaifId": 301,
                "axes": "J2000",
                "aberrationCorrection": "NONE",
                "positionUnits": "m",
                "velocityUnits": "m/s",
            },
            "referenceEpochJ2000Seconds": start_et,
            "referenceEpochNote": (
                "SPICE ephemeris time seconds past J2000 TDB; celestial-body rendering still "
                "comes from Perilune's analytic universe, not this SPK."
            ),
            "sourceEpochTdb": spice.timout(start_et, "YYYY-MM-DDTHR:MN:SC.###### ::TDB"),
            "sourceEpochUtc": spice.et2utc(start_et, "ISOC", 6),
            "durationSeconds": duration,
            "sampleStepSeconds": step,
            "interpolation": "cubic-hermite",
            "loopMode": "open-reference-revolution",
            "generatedFrom": {
                "sourceLockPath": "assets/missions/artemis-iv/sources/source.lock.json",
                "kernelSourceIds": kernel_source_ids,
                "kernelArtifacts": locked_kernel_artifacts,
                "spiceTargetNaifId": -60000,
                "spiceObserverNaifId": 301,
                "generatorScript": "scripts/compile-artemis-reference-track.py",
                "requirements": "scripts/requirements-artemis-reference.txt",
                "spiceypyVersion": spice.__version__,
                "numpyVersion": numpy.__version__,
            },
            "metrics": {
                "sampleCount": len(samples),
                "periodDays": period_days,
                "minimumRadiusMeters": minimum_radius,
                "maximumRadiusMeters": maximum_radius,
                "endpointSeparationMeters": endpoint_separation,
                "endpointVelocityDeltaMetersPerSecond": endpoint_velocity_delta,
                "publishedAveragePeriodDays": 6.562,
                "publishedPeriluneRadiusRangeMeters": [3_196_000, 3_557_000],
                "publishedApoluneRadiusApproxMeters": 70_000_000,
            },
            "samplesSha256": sample_digest(samples),
            "samples": samples,
        }
    finally:
        spice.kclear()


def encoded_artifact(artifact: dict[str, Any]) -> bytes:
    return (json.dumps(artifact, indent=2, sort_keys=True, allow_nan=False) + "\n").encode("utf-8")


def main() -> int:
    args = parse_args()
    lock = json.loads(args.source_lock.read_text(encoding="utf-8"))
    artifact_bytes = encoded_artifact(compile_artifact(lock, args.kernel_dir))
    artifact_digest = hashlib.sha256(artifact_bytes).hexdigest()

    if args.check:
        if not args.output.is_file():
            raise FileNotFoundError(f"Checked artifact is missing: {args.output}")
        checked_bytes = args.output.read_bytes()
        if checked_bytes != artifact_bytes:
            raise ValueError(
                f"Checked artifact is stale: expected SHA-256 {artifact_digest}, "
                f"got {hashlib.sha256(checked_bytes).hexdigest()}"
            )
        print(f"Artemis reference artifact is current: {artifact_digest}")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    partial = args.output.with_name(f"{args.output.name}.partial-{os.getpid()}")
    partial.write_bytes(artifact_bytes)
    partial.replace(args.output)
    print(
        f"wrote {args.output}: {len(artifact_bytes)} bytes, SHA-256 {artifact_digest}"
    )
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as error:
        print(f"Artemis reference track compilation failed: {error}", file=sys.stderr)
        raise SystemExit(1) from error

import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import {
  deriveScientificHeight,
  encodeHalfMetreInt16,
  HEIGHT_SOURCE_DEFINITIONS,
  sourceSha256,
} from './lib/scientific-height-derivation.mjs';
import {
  checkedHeightArtifactDigest,
  checkedHeightGridFromEntry,
} from './lib/height-authority-artifact.mjs';

const ROOT = process.cwd();
const WIDTH = 512;
const HEIGHT = 256;
const INPUTS = Object.freeze({
  earth: HEIGHT_SOURCE_DEFINITIONS.earthSurface,
  moon: HEIGHT_SOURCE_DEFINITIONS.moon,
});

const entries = [];
for (const [bodyId, definition] of Object.entries(INPUTS)) {
  const derivative = await deriveScientificHeight(ROOT, definition, WIDTH, HEIGHT);
  const quantized = encodeHalfMetreInt16(derivative.heights);
  entries.push({
    bodyId,
    sourceId: definition.sourceId,
    sourcePath: definition.relativePath,
    sourceSha256: await sourceSha256(ROOT, definition),
    sourceDimensions: definition.sourceDimensions,
    verticalDatum: definition.verticalDatum,
    derivationKernel: derivative.kernel,
    width: WIDTH,
    height: HEIGHT,
    minimum: derivative.minimum,
    maximum: derivative.maximum,
    noDataCount: derivative.noDataCount,
    quantizationScaleMeters: quantized.scaleMeters,
    quantizationOffsetMeters: quantized.offsetMeters,
    worstQuantizationErrorMeters: quantized.worstQuantizationErrorMeters,
    rmsQuantizationErrorMeters: quantized.rmsQuantizationErrorMeters,
    data: quantized.encoded.toString('base64'),
  });
}

const serialized = JSON.stringify(entries, null, 2);
const digest = createHash('sha256').update(serialized).digest('hex');
const grids = entries.map(checkedHeightGridFromEntry);
const artifactDigest = checkedHeightArtifactDigest(grids);
const output = `/** Generated by scripts/compile-height-authority.mjs. Do not edit. */
export const CHECKED_HEIGHT_AUTHORITY_VERSION = '${digest}' as const;
export const CHECKED_HEIGHT_ARTIFACT_SHA256 = '${artifactDigest}' as const;
export interface CheckedHeightGrid {
  readonly bodyId: 'earth' | 'moon';
  readonly sourceId: string;
  readonly sourcePath: string;
  readonly sourceSha256: string;
  readonly sourceDimensions: readonly [number, number];
  readonly verticalDatum: string;
  readonly derivationKernel: 'lanczos3';
  readonly width: number;
  readonly height: number;
  readonly minimumHeightMeters: number;
  readonly maximumHeightMeters: number;
  readonly noDataCount: number;
  readonly quantizationScaleMeters: number;
  readonly quantizationOffsetMeters: number;
  readonly worstQuantizationErrorMeters: number;
  readonly rmsQuantizationErrorMeters: number;
  /** Signed little-endian Int16 samples in the declared scale and offset. */
  readonly encodedInt16Base64: string;
}
export const CHECKED_HEIGHT_GRIDS: readonly CheckedHeightGrid[] = Object.freeze([
${grids.map((entry) => `  Object.freeze({
    bodyId: '${entry.bodyId}', sourceId: '${entry.sourceId}',
    sourcePath: '${entry.sourcePath}', sourceSha256: '${entry.sourceSha256}',
    sourceDimensions: Object.freeze([${entry.sourceDimensions[0]}, ${entry.sourceDimensions[1]}]) as readonly [number, number],
    verticalDatum: '${entry.verticalDatum}', derivationKernel: '${entry.derivationKernel}',
    width: ${entry.width}, height: ${entry.height}, noDataCount: ${entry.noDataCount},
    minimumHeightMeters: ${entry.minimumHeightMeters.toFixed(6)}, maximumHeightMeters: ${entry.maximumHeightMeters.toFixed(6)},
    quantizationScaleMeters: ${entry.quantizationScaleMeters}, quantizationOffsetMeters: ${entry.quantizationOffsetMeters},
    worstQuantizationErrorMeters: ${entry.worstQuantizationErrorMeters.toFixed(9)},
    rmsQuantizationErrorMeters: ${entry.rmsQuantizationErrorMeters.toFixed(9)},
    encodedInt16Base64: '${entry.encodedInt16Base64}',
  }),`).join('\n')}
]);
`;
const outputPath = path.join(ROOT, 'src/generated/checked-height-authority.ts');
if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== output) {
    throw new Error('checked-height-authority.ts is stale; run npm run compile:height-authority');
  }
  console.log(`Checked ${path.relative(ROOT, outputPath)} direct source hashes (${digest})`);
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output);
  console.log(`Wrote ${path.relative(ROOT, outputPath)} direct numeric authority (${WIDTH}x${HEIGHT}, ${digest})`);
}

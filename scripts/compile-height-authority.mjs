import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = process.cwd();
const WIDTH = 512;
const HEIGHT = 256;
const INPUTS = Object.freeze({
  earth: 'assets/planets/generated/earth/medium/heightMacro.png',
  moon: 'assets/planets/generated/moon/medium/heightMacro.png',
});

function decodeHeight(red, green) {
  return -12_000 + (red * 256 + green) / 65_535 * 24_000;
}

const entries = [];
for (const [bodyId, relativePath] of Object.entries(INPUTS)) {
  const absolutePath = path.join(ROOT, relativePath);
  const source = await readFile(absolutePath);
  const { data, info } = await sharp(source)
    .resize(WIDTH, HEIGHT, { kernel: sharp.kernel.nearest })
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  if (info.channels < 2) throw new Error(`${relativePath} must preserve the RG height encoding`);
  const encoded = Buffer.allocUnsafe(WIDTH * HEIGHT * 2);
  let minimum = Infinity;
  let maximum = -Infinity;
  for (let index = 0; index < WIDTH * HEIGHT; index++) {
    const height = decodeHeight(data[index * info.channels], data[index * info.channels + 1]);
    minimum = Math.min(minimum, height);
    maximum = Math.max(maximum, height);
    encoded.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(height * 2))), index * 2);
  }
  entries.push({
    bodyId,
    sourcePath: relativePath,
    sourceSha256: createHash('sha256').update(source).digest('hex'),
    width: WIDTH,
    height: HEIGHT,
    minimum,
    maximum,
    data: encoded.toString('base64'),
  });
}

const serialized = JSON.stringify(entries, null, 2);
const digest = createHash('sha256').update(serialized).digest('hex');
const output = `/** Generated by scripts/compile-height-authority.mjs. Do not edit. */
export const CHECKED_HEIGHT_AUTHORITY_VERSION = '${digest}' as const;
export interface CheckedHeightGrid {
  readonly bodyId: 'earth' | 'moon';
  readonly sourcePath: string;
  readonly sourceSha256: string;
  readonly width: number;
  readonly height: number;
  readonly minimumHeightMeters: number;
  readonly maximumHeightMeters: number;
  /** Signed little-endian Int16 samples in half-metre units. */
  readonly encodedInt16Base64: string;
}
export const CHECKED_HEIGHT_GRIDS: readonly CheckedHeightGrid[] = Object.freeze([
${entries.map((entry) => `  Object.freeze({
    bodyId: '${entry.bodyId}', sourcePath: '${entry.sourcePath}', sourceSha256: '${entry.sourceSha256}',
    width: ${entry.width}, height: ${entry.height},
    minimumHeightMeters: ${entry.minimum.toFixed(3)}, maximumHeightMeters: ${entry.maximum.toFixed(3)},
    encodedInt16Base64: '${entry.data}',
  }),`).join('\n')}
]);
`;
const outputPath = path.join(ROOT, 'src/generated/checked-height-authority.ts');
await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, output);
console.log(`Wrote ${path.relative(ROOT, outputPath)} (${WIDTH}x${HEIGHT}, ${digest})`);

/**
 * Perilune part catalog — original part designs for the Skyward Cooperative.
 *
 * Every part has procedural geometry (cylinders/cones/panels with PBR
 * materials) as its guaranteed render fallback. Selected parts additionally
 * carry a `modelAssetId` naming a checked NASA-style render model (see
 * docs/DEVELOPMENT.md); the shared part-model library swaps that model in when
 * loaded, but `PartShape` remains the sole authority for physics, mass, and
 * attachments regardless of which visual renders. Sizes: stack class
 * S = 0.6 m radius, M = 1.25 m radius.
 */

export type ResourceId = 'propellant' | 'solidFuel' | 'monoprop' | 'charge' | 'ablator' | 'ore';

export type TechId =
  | 'foundations'
  | 'orbital-engineering'
  | 'atmospheric-flight'
  | 'exploration-instruments'
  | 'deep-space-systems'
  | 'surface-operations'
  | 'precision-science'
  | 'crewed-expeditions'
  | 'planetary-industry';

export const RESOURCE_DENSITY: Record<ResourceId, number> = {
  propellant: 5, // kg per unit
  solidFuel: 7.5,
  monoprop: 4,
  charge: 0, // massless
  ablator: 1,
  ore: 6, // raw regolith concentrate
};

export interface PartShape {
  kind: 'cylinder' | 'cone' | 'capsule' | 'box' | 'panel' | 'dome';
  /** For cylinders/cones: radii (m). Cone: top < bottom allowed either way. */
  radiusTop?: number;
  radiusBottom?: number;
  height: number;
  /** For boxes/panels: full extents (m). */
  width?: number;
  depth?: number;
}

export interface EngineDef {
  thrustVac: number; // N
  ispVac: number; // s
  ispSea: number; // s
  gimbalDeg: number;
  propellant: 'propellant' | 'solidFuel';
  minThrottle: number; // 0..1 (solid boosters: 1 = unthrottleable)
  /** Exhaust visual scale. */
  plumeScale: number;
  /**
   * Air-breathing: thrust scales with air density and vanishes in vacuum.
   * `thrustVac` is then the rated sea-level thrust.
   */
  airBreathing?: boolean;
}

export interface DecouplerDef {
  ejection: number;
  /** Separators release every attached edge; decouplers release their payload side. */
  mode: 'decoupler' | 'separator';
  radial?: boolean;
  /** Generate one detachable shroud from the connected stack envelopes. */
  interstage?: boolean;
}

export interface PartDef {
  id: string;
  tech: TechId;
  name: string;
  blurb: string;
  category:
    | 'pods'
    | 'tanks'
    | 'engines'
    | 'coupling'
    | 'structural'
    | 'aero'
    | 'utility'
    | 'science'
    | 'thermal'
    | 'ground';
  massDry: number; // kg
  cost: number;
  shape: PartShape;
  /** Stack attachment nodes at top/bottom of the shape. */
  stackTop?: boolean;
  stackBottom?: boolean;
  /** Part can be surface-attached onto another part. */
  surfaceAttach?: boolean;
  /** Other parts may surface-attach onto this part. */
  acceptsSurfaceAttach?: boolean;
  /** Fuel may flow through this part. */
  crossfeed: boolean;
  maxTemp: number; // K
  crashTolerance: number; // m/s
  /** Multiplies the structural rating of joints touching this reinforced fitting. */
  jointStrengthMultiplier?: number;
  resources?: Partial<Record<ResourceId, number>>;
  engine?: EngineDef;
  rcs?: { thrust: number };
  pod?: { crew: number; torque: number };
  probe?: { torque: number };
  decoupler?: DecouplerDef;
  parachute?: { dragArea: number; semiDeployAlt: number; deployAlt: number };
  wing?: { liftArea: number; control?: boolean; maxDeflection?: number };
  battery?: { capacity: number };
  solar?: { chargeRate: number };
  antenna?: { range: number; rate: number };
  science?: { experimentId: string };
  heatShield?: boolean;
  leg?: { length: number; strength: number };
  reactionWheel?: { torque: number };
  /** Ground wheel: sphere contact of `radius` at the part center. */
  wheel?: {
    radius: number; // m
    driveForce: number; // N of traction at full drive (0 = free-rolling gear)
    maxSpeed: number; // m/s driven speed limit
    steering: boolean;
    brakeForce: number; // N
  };
  /** Surface drill: extracts ore from deposits when landed. */
  drill?: { rate: number; power: number }; // ore units/s, charge/s
  /** Orbital resource scanner: reveals deposits from orbit. */
  resourceScanner?: { power: number };
  /** Refinery: converts ore into propellant. */
  converter?: { rate: number; power: number; yield: number }; // ore units/s in, propellant = rate·yield
  /** Ore storage capacity (bins start empty, unlike fuel tanks). */
  oreCapacity?: number;
  color?: string;
  accent?: string;
  /**
   * Optional checked NASA-style render model. The renderer swaps in this model
   * when the shared library has it loaded; procedural geometry stays the
   * guaranteed fallback and remains the sole authority for physics/attachments.
   */
  modelAssetId?: string;
}


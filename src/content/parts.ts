export const PART_INDEX: ReadonlyMap<string, PartDef> = new Map(PARTS.map((p) => [p.id, p]));

export function partById(id: string): PartDef {
  const def = PART_INDEX.get(id);
  if (!def) throw new Error(`Unknown part: ${id}`);
  return def;
}

/** Full (wet) mass of a part def with given resource amounts. */
export function partMass(def: PartDef, resources?: Partial<Record<ResourceId, number>>): number {
  let m = def.massDry;
  const res = resources ?? def.resources;
  if (res) {
    for (const key of Object.keys(res) as ResourceId[]) {
      m += (res[key] ?? 0) * RESOURCE_DENSITY[key];
    }
  }
  return m;
}
